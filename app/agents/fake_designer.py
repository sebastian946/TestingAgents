"""Deterministic stand-in for Claude, enabled with DESIGNER_MODE=fake (WTA-24).

The end-to-end integration test runs the API and the worker as separate processes, as in
production, so it cannot monkeypatch the LLM away: the switch has to be configuration. In
fake mode the Designer builds scenarios from the page inventory with fixed rules, so a job
goes through the whole pipeline (crawl, design, persist, report) with no API key, no
network to Anthropic, no cost, and the same output every run.

It is NOT a test-design strategy for real customers: the worker prints a warning when it
starts in this mode, and every scenario says it was generated by the fake Designer.
"""
from typing import Any

from models.agent_models import TestScenario

FAKE_MODEL = "fake-designer"

TEXTS = {
    "en": {
        "submit": "Submitting the {form} form with valid data works",
        "submit_steps": ["Open {url}", "Fill every field with valid data", "Click {submit}"],
        "submit_expected": "The form is accepted and the page shows a confirmation or the next step",
        "empty": "{label} is required",
        "empty_steps": ["Open {url}", "Leave {label} empty and fill the other fields", "Click {submit}"],
        "empty_expected": "The form is not submitted and {label} shows an error",
        "password": "A wrong password is rejected",
        "password_steps": ["Open {url}", "Type <valid username> and a wrong password", "Click {submit}"],
        "password_expected": "Access is denied and an error message is shown",
        "loads": "The page loads with its main content",
        "loads_steps": ["Open {url}"],
        "loads_expected": "The page shows {heading} with no errors",
        "the_page": "the page",
        "form": "page",
        "submit_button": "the submit button",
    },
    "es": {
        "submit": "Enviar el formulario de {form} con datos válidos funciona",
        "submit_steps": ["Abrir {url}", "Completar todos los campos con datos válidos", "Hacer clic en {submit}"],
        "submit_expected": "El formulario se acepta y la página muestra una confirmación o el siguiente paso",
        "empty": "{label} es obligatorio",
        "empty_steps": ["Abrir {url}", "Dejar {label} vacío y completar los demás campos", "Hacer clic en {submit}"],
        "empty_expected": "El formulario no se envía y {label} muestra un error",
        "password": "Una contraseña incorrecta se rechaza",
        "password_steps": ["Abrir {url}", "Escribir <usuario válido> y una contraseña incorrecta", "Hacer clic en {submit}"],
        "password_expected": "Se niega el acceso y se muestra un mensaje de error",
        "loads": "La página carga con su contenido principal",
        "loads_steps": ["Abrir {url}"],
        "loads_expected": "La página muestra {heading} sin errores",
        "the_page": "la página",
        "form": "la página",
        "submit_button": "el botón de envío",
    },
}


def fake_scenarios(url: str, page_type: str | None, elements: dict[str, Any] | None, language: str = "en") -> list[TestScenario]:
    """Scenarios derived from the inventory with fixed rules: same page, same scenarios."""
    t = TEXTS.get(language, TEXTS["en"])
    elements = elements or {}
    scenarios: list[TestScenario] = []

    for form in elements.get("forms", []):
        fields = form.get("fields", [])
        submit = form.get("submit_text") or t["submit_button"]
        form_name = page_type or t["form"]
        has_password = any(f.get("type") == "password" for f in fields)
        scenarios.append(TestScenario(
            title=t["submit"].format(form=form_name),
            steps=[s.format(url=url, submit=submit) for s in t["submit_steps"]],
            expected_result=t["submit_expected"],
            priority="critical" if has_password else "high",
            category="functional",
        ))
        if has_password:
            scenarios.append(TestScenario(
                title=t["password"],
                steps=[s.format(url=url, submit=submit) for s in t["password_steps"]],
                expected_result=t["password_expected"],
                priority="critical",
                category="security",
            ))
        for field in fields:
            if not field.get("required"):
                continue
            label = field.get("label") or field.get("name") or field.get("id") or field.get("type")
            scenarios.append(TestScenario(
                title=t["empty"].format(label=label),
                steps=[s.format(url=url, label=label, submit=submit) for s in t["empty_steps"]],
                expected_result=t["empty_expected"].format(label=label),
                priority="high" if has_password else "medium",
                category="validation",
            ))

    if not scenarios:
        heading = (elements.get("headings") or [t["the_page"]])[0]
        scenarios.append(TestScenario(
            title=t["loads"],
            steps=[s.format(url=url) for s in t["loads_steps"]],
            expected_result=t["loads_expected"].format(heading=heading),
            priority="low",
            category="functional",
        ))

    # Titles must be unique per page (DesignerOutput rule); keep the first of any repeat
    seen: set[str] = set()
    return [s for s in scenarios if not (s.title.casefold() in seen or seen.add(s.title.casefold()))][:12]
